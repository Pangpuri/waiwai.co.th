/** โหมดเขียนภาพ: `keep` = คงค่าเดิม · `set` = เขียนค่าที่ส่งมา (รวม NULL = ลบ) */
export type ImageWriteMode = "keep" | "set";

/**
 * เลือกโหมดเขียนภาพจากฟอร์ม
 *
 * @param formData ฟอร์มที่รับมา
 * @param key ชื่อคีย์ของภาพ (เช่น `imagePath` · `logoPath` · `coverPath`)
 * @returns `"set"` เมื่อ **มีคีย์นั้นในฟอร์ม** (แม้ค่าว่าง = ผู้ใช้สั่งลบ) · `"keep"` เมื่อไม่มีคีย์เลย
 */
export function imageWriteMode(formData: FormData, key: string): ImageWriteMode {
  return formData.has(key) ? "set" : "keep";
}
