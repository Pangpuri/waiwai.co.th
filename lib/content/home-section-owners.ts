/**
 * "ส่วนไหนของหน้าแรกแก้ที่ไหน" — รอบที่ 226 · ปรับปรุงรอบ 330
 *
 * ปัญหาที่เจ้าของชี้: *"เคลียส่วนซ้ำซ้อนก่อนเลยครับ ผู้นำไปใช้เข้าใจผิดง่าย"*
 * หน้าจอ `/admin/content/home` เคยเปิดฟิลด์ของ **ทุกส่วน** แต่ของจริงหน้าเว็บอ่านค่าเพียงบางส่วน
 * ⇒ ฟิลด์ที่เหลือกลายเป็น **UI หลอกตา** และซ้ำกับที่อื่น (ตัวสร้างหน้าเว็บ/เมนูสไลด์/ฐานข้อมูล)
 * ★ รอบ 330: **ถอดหน้าจอนั้นออกแล้ว** — ทะเบียนนี้เก็บไว้เป็นเอกสาร/เทสต์ว่าแต่ละส่วนมีเจ้าของที่ไหน
 *
 * กติกา (แหล่งความจริงเดียวต่อส่วน)
 * - `whereToBuy` = **แก้ที่บล็อก "ที่ซื้อสินค้า" ในตัวสร้างหน้าเว็บ** (รอบ 329)
 * - ส่วนอื่น = แสดงจากระบบอื่น (ตัวสร้างหน้าเว็บ · เมนูสไลด์ · ฐานข้อมูล · ตั้งค่า SEO)
 *
 * ตรรกะล้วน ⇒ ทดสอบได้ด้วย `node --test`
 */
export type SectionOwner = {
  /** คีย์ของส่วนใน `HOME_SECTIONS` */
  readonly key: string;
  /** หน้าจอที่ "เป็นเจ้าของ" ค่าจริง */
  readonly screen: string;
  /**
   * ซ่อนฟอร์มของส่วนนี้จากหน้าจอนี้เลย (ไม่ใช่แค่เตือน) — รอบที่ 251
   *
   * มติเจ้าของ 2026-10-09: *"รวมทุกอย่างของ hero ไว้ที่สไลด์ & แคมเปญ"*
   * ⇒ หน้าจอสไลด์เป็นเจ้าของส่วน hero ทั้งส่วน (สไลด์ · การ์ด · ข้อความ · ปุ่ม)
   * ⚠️ ค่ายังอยู่ใน draft ⇒ กดบันทึกจากหน้าจอนี้แล้วค่า hero ไม่หาย (มีเทสต์คุม)
   */
  readonly hideForm?: boolean;
  /**
   * **ส่วนนี้เลิกใช้แล้ว** — หน้าเว็บไม่อ่านค่าจากแถว EAV เหล่านี้อีกเลย (รอบที่ 252 · ตรวจด้วยการค้นซอร์สจริง)
   *
   * ที่มา: หลังย้ายหน้าแรกไปใช้ **บล็อก** (รอบ 211–224) + **ฐานข้อมูล** + **ตั้งค่าส่วนกลาง**
   * ข้อมูลจริงของส่วนเหล่านี้มาจากที่อื่นทั้งหมด ⇒ ฟอร์มในหน้านี้เคยเป็น "ช่องที่กรอกแล้วไม่มีผล"
   * ⇒ ซ่อนฟอร์ม + บอกว่าแหล่งจริงอยู่ที่ไหน · ⚠️ **ไม่ลบข้อมูล** (แถวยังอยู่ ค่ายังไม่หาย)
   */
  readonly dead?: boolean;
  /**
   * ค่าที่กรอกในหน้านี้ **มีผลเฉพาะเมื่อหน้าแรกยังใช้เลย์เอาต์โค้ด** (โหมดยังไม่เปิดบล็อก)
   *
   * ⚠️ รอบ 329: ไม่มีส่วนไหนใช้ค่านี้แล้ว (whereToBuy ย้ายไปบล็อก) — เก็บไว้เป็นทางเลือกของอนาคต
   *    ถ้ามีส่วนที่ต้องใช้ทั้งสองโหมดจริง ๆ ค่อยเปิดใช้
   */
  readonly codeLayoutOnly?: boolean;
};

export const HOME_SECTION_OWNERS: readonly SectionOwner[] = [
  /* หัวหน้าแรก + สไลด์ + การ์ด PR: เจ้าของคือเมนู "สไลด์ แคมเปญ ข้อความหัวเว็บไซต์" (รอบ 217 · 251) */
  { key: "hero", screen: "/admin/hero", hideForm: true },
  /*
    ★ รอบ 329 (คำเจ้าของ): "ที่ซื้อสินค้า" ย้ายไปอยู่กับ **บล็อกที่ซื้อสินค้า** ในตัวสร้างหน้าเว็บ
    เพราะปุ่มลิงก์ร้านเป็นของส่วนนี้ ⇒ หน้าจอเนื้อหาเดิมเลิกแสดงฟอร์ม (ข้อมูล EAV ยังอยู่ ไม่ลบ)
  */
  { key: "whereToBuy", screen: "/admin/builder/home", dead: true },
  /* ข้อมูลจริงมาจากฐานข้อมูล + บล็อกในตัวสร้างหน้าเว็บ (สองทางนี้เป็นเจ้าของ) */
  { key: "products", screen: "/admin/builder/home", dead: true },
  { key: "recipes", screen: "/admin/builder/home", dead: true },
  { key: "news", screen: "/admin/builder/home", dead: true },
  { key: "newsletter", screen: "/admin/builder/home", dead: true },
  /* SEO รายหน้า: เจ้าของคือหน้าตั้งค่าส่วนกลาง */
  { key: "seo", screen: "/admin/settings", dead: true },
];

/** ส่วนนี้ถูกดูแลที่อื่นไหม (คืน null = หน้านี้เป็นเจ้าของค่าจริง) */
export function ownerOfSection(key: string): SectionOwner | null {
  return HOME_SECTION_OWNERS.find((entry) => entry.key === key) ?? null;
}

