/**
 * สถานะ "เปิดทีละรายการ" ของ accordion ในตัวแก้แถบเมนู (รอบที่ 319)
 *
 * *"พับรายการเมนูแต่ละอันเป็น accordion (เปิดทีละอัน) — จะลดความยาวของ navbar editor ได้มาก"*
 *
 * กติกา
 * - คลิกรายการที่ยังปิดอยู่ ⇒ เปิดรายการนั้น **และปิดรายการเดิมเอง** (มีค่าเดียว)
 * - คลิกรายการที่เปิดอยู่ซ้ำ ⇒ ปิด (กลับไปไม่มีอะไรเปิด)
 * - `null` = ไม่มีรายการเปิด
 *
 * แยกเป็นฟังก์ชันบริสุทธิ์เพื่อทดสอบกติกาโดยไม่ต้องพึ่ง DOM
 */
export function toggleOpenId(current: string | null, clicked: string): string | null {
  return current === clicked ? null : clicked;
}
