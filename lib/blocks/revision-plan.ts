/** เก็บรุ่นล่าสุดต่อหน้าไว้ไม่เกินกี่รุ่น (ตัวที่เกินจะถูกลบเมื่อเผยแพร่ครั้งถัดไป) */
export const MAX_PAGE_REVISIONS = 25;

/**
 * จำนวนรุ่นที่แสดงในแผงประวัติของหลังบ้าน
 * ⚠️ ต้อง ≤ `MAX_PAGE_REVISIONS` ไม่งั้นผู้ใช้จะเห็นรุ่นที่กำลังจะถูกลบปนกัน
 */
export const HISTORY_PANEL_LIMIT = 20;

/** ค่าที่ต้องส่งมาในช่อง `confirm` ก่อนล้างประวัติ (กันกดพลาด) */
export const PRUNE_HISTORY_CONFIRM_VALUE = "prune";

/**
 * รุ่นไหนควรถูกลบ อิงจาก "เก็บรุ่นล่าสุดไว้กี่รุ่น"
 * @param revisions เลขรุ่นที่มีอยู่ (ลำดับใดก็ได้ · ซ้ำได้ — จะถูกตัดออกให้)
 * @param keep จำนวนรุ่นล่าสุดที่ต้องเก็บ — **ค่าที่ไม่ใช่จำนวนเต็มบวก (0/ติดลบ/NaN) จะถอยไปใช้เพดานนโยบาย**
 *   (ปลอดภัยกว่า: ค่าพังต้อง *ลบน้อยลง* ไม่ใช่ลบมากขึ้น · และห้ามลบจนไม่เหลือรุ่น)
 * @returns เลขรุ่นที่ควรลบ เรียงจากน้อยไปมาก
 */
export function revisionNumbersToPrune(revisions: readonly number[], keep: number = MAX_PAGE_REVISIONS): readonly number[] {
  const safeKeep = Number.isInteger(keep) && keep >= 1 ? keep : MAX_PAGE_REVISIONS;
  const unique = [...new Set(revisions)].sort((a, b) => b - a);
  return unique.slice(safeKeep).reverse();
}
