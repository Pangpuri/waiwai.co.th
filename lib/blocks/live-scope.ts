/**
 * หน้าที่ "เผยแพร่ = ขึ้นเว็บทันที" (home · about — มติเจ้าของ 2026-10-09 · **executives = รอบที่ 259**)
 *
 * ⚠️ **executives (รอบที่ 259 · มติ 2026-10-10):** เจ้าของสั่ง *"เก็บภาพลง db ตามโครงสร้างหน้าบ้าน …
 *    โครงหลังบ้านก็อิงตามหน้าบ้าน"* ⇒ หน้า "คณะผู้บริหาร" ต้องแก้จากหลังบ้านแล้วเห็นผลบนเว็บได้
 *    ⇒ เข้ารายการนี้ (กดเผยแพร่ = ขึ้นเว็บ + สั่งสร้างหน้าใหม่)
 *
 * ⚠️ **certifications (รอบที่ 262 · มติ 2026-10-10):** เจ้าของสั่งให้หน้า "ใบรับรองมาตรฐาน"
 *    เหลือแต่ภาพจากฐานข้อมูล ⇒ ต้องแก้/เพิ่มภาพจากหลังบ้านแล้วเห็นผลบนเว็บได้
 */
export const PUBLISH_GOES_LIVE_PAGES = ["home", "about", "executives", "certifications"] as const;

/** หน้านี้กดเผยแพร่แล้วหน้าเว็บจะเปลี่ยนทันทีหรือไม่ */
export function publishGoesLive(page: string): boolean {
  return (PUBLISH_GOES_LIVE_PAGES as readonly string[]).includes(page);
}

/** ผลลัพธ์ที่ผู้ใช้ต้องเห็นหลังกดเผยแพร่ — คืน "รหัส" ไม่ใช่ข้อความ (ข้อความมาจากพจนานุกรม) */
export type PublishOutcome = "goes-live" | "saved-only";

export function publishOutcomeOf(page: string): PublishOutcome {
  return publishGoesLive(page) ? "goes-live" : "saved-only";
}

/**
 * ตรวจว่าสถานะสวิตช์ใน DB ตรงกับนโยบายหรือยัง (ใช้เป็นด่านใน `check:db`)
 * - หน้าที่ "เผยแพร่ = ขึ้นเว็บ" → คาดหวัง `true`
 * - หน้าที่เหลือ → คาดหวัง `false` (ยังไม่เปิดขึ้นเว็บ)
 */
export function expectedLiveOf(page: string): boolean {
  return publishGoesLive(page);
}
