-- ปัญหาที่ปิด
--   คุกกี้เซสชันเดิมเป็น "โทเคนที่เซ็นชื่อ" แบบไม่เก็บสถานะ (stateless) ⇒ **ยกเลิกไม่ได้**
--   ปิดบัญชี/ลบบัญชี/ตั้งรหัสผ่านใหม่ = คนที่ถือคุกกี้เดิมยังใช้งานได้จนหมดอายุ (≤8 ชม.)
--   และผู้ดูแลไม่มีทางเห็นว่า "ตอนนี้มีใครล็อกอินอยู่บ้าง"
--
-- ทางออก (ตรงกับที่ `db/schema.sql` ประกาศไว้ตั้งแต่เฟส B1 — ตอนนี้ทำจริง)
--   · คุกกี้ที่เซ็นแล้วมีรหัสเซสชัน (`sid`) เพิ่มขึ้น · ฐานข้อมูลเก็บ **sha256(sid)** ไม่เก็บค่าดิบ
--     ⇒ ถ้าฐานข้อมูลรั่ว ผู้โจมตีเอา hash ไปสวมรอยไม่ได้ (ต้องมีลายเซ็น HMAC ของคุกกี้ด้วย)
--   · ตรวจทุกคำขอ (`getSessionUser`) ว่าแถวยัง "ใช้งานได้" = ไม่ถูกเพิกถอน + ไม่หมดอายุ + บัญชียังไม่ถูกปิด
--   · ผู้ดูแลเห็นรายการเซสชันที่ล็อกอินอยู่ และ **ตัดเซสชัน**ได้ทันที (รายตัว/ทั้งบัญชี)
--   · `on delete cascade` ⇒ ลบบัญชี = เซสชันหายตาม (ปิดบัญชี/ตั้งรหัสใหม่ = เพิกถอนในโค้ด)
--
-- ⚠️ **ไม่เก็บ IP** (เก็บเฉพาะ user-agent ที่ตัดความยาวแล้ว) — ลดข้อมูลส่วนบุคคลโดยไม่เสียประโยชน์
-- ⚠️ ร่องรอยของเจ้าหน้าที่ · ระยะเก็บ 30 วันหลังหมดอายุ/ถูกเพิกถอน (`lib/retention/plan.ts` · ชั้น `adminSession`)
-- ⚠️ idempotent ทุกคำสั่ง
-- ─────────────────────────────────────────────────────────────────────────────

create table if not exists admin_session (
  /** sha256 ของรหัสเซสชัน (ค่าดิบอยู่ในคุกกี้ที่เซ็นแล้วเท่านั้น) */
  token_hash   text        primary key,
  user_id      text        not null references admin_user (id) on delete cascade,
  created_at   timestamptz not null default now(),
  /** เห็นล่าสุดเมื่อไร (อัปเดตแบบไม่ถี่ — ให้ "รายการเซสชัน" มีข้อมูลจริงโดยไม่เขียนทุกคำขอ) */
  last_seen_at timestamptz not null default now(),
  expires_at   timestamptz not null,
  /** เวลาที่ถูกเพิกถอน (null = ยังใช้งานได้) */
  revoked_at   timestamptz,
  revoked_by   text,
  /** คำใบ้อุปกรณ์/เบราว์เซอร์ (ตัด 200 ตัวอักษร) — ไม่เก็บ IP */
  user_agent   text
);

create index if not exists admin_session_user_idx   on admin_session (user_id, created_at desc);
create index if not exists admin_session_active_idx on admin_session (expires_at) where revoked_at is null;

